const DICT: Record<Lang, Partial<Record<CopyKey, string>>> = { en, si, ta };

export function translate(lang: Lang, key: CopyKey): string {
  return DICT[lang][key] ?? en[key];
}

export function useI18n() {
  const lang = usePrefs((state) => state.lang);
  return {
    lang,
    t: (key: CopyKey) => translate(lang, key),
    n: (value: Localized) => value[lang] || value.en,
  };
}
